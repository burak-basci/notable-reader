#!/usr/bin/env python3
"""
OAuth 2.0 Flow to Obtain Chrome Web Store Refresh Token.

Run this once to get a long-lived refresh token for automated uploads.
The refresh token is stored in .env.cws (gitignored).

Prerequisites:
1. Google Cloud Console project with Chrome Web Store API enabled
2. OAuth 2.0 Client ID (Web application type)
3. Authorized redirect URI: http://localhost:8080/callback

Usage:
    python3 tools/get-cws-refresh-token.py --client-id YOUR_ID --client-secret YOUR_SECRET
"""

import argparse
import json
import secrets
import sys
import urllib.parse
import urllib.request
from http.server import HTTPServer, BaseHTTPRequestHandler
from pathlib import Path
from threading import Thread
from typing import Optional

# OAuth endpoints
AUTH_URL = "https://accounts.google.com/o/oauth2/v2/auth"
TOKEN_URL = "https://oauth2.googleapis.com/token"
SCOPES = ["https://www.googleapis.com/auth/chromewebstore"]


class CallbackHandler(BaseHTTPRequestHandler):
    """Handle OAuth callback."""
    auth_code: Optional[str] = None
    error: Optional[str] = None

    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        params = urllib.parse.parse_qs(parsed.query)

        if "code" in params:
            CallbackHandler.auth_code = params["code"][0]
            self.send_response(200)
            self.send_header("Content-Type", "text/html")
            self.end_headers()
            self.wfile.write(b"<h1>Authorization successful!</h1><p>You can close this window.</p>")
        elif "error" in params:
            CallbackHandler.error = params["error"][0]
            self.send_response(400)
            self.send_header("Content-Type", "text/html")
            self.end_headers()
            self.wfile.write(f"<h1>Authorization failed: {CallbackHandler.error}</h1>".encode())
        else:
            self.send_response(400)
            self.end_headers()

    def log_message(self, format, *args):
        pass  # Suppress default log messages


def run_local_server(port: int = 8080) -> str:
    """Run local HTTP server to receive OAuth callback."""
    server = HTTPServer(("localhost", port), CallbackHandler)
    thread = Thread(target=server.serve_forever, daemon=True)
    thread.start()

    # Wait for callback
    while CallbackHandler.auth_code is None and CallbackHandler.error is None:
        import time
        time.sleep(0.1)

    server.shutdown()
    server.server_close()

    if CallbackHandler.error:
        raise RuntimeError(f"OAuth error: {CallbackHandler.error}")

    if not CallbackHandler.auth_code:
        raise RuntimeError("No authorization code received")

    return CallbackHandler.auth_code


def exchange_code_for_tokens(client_id: str, client_secret: str, code: str, redirect_uri: str) -> dict:
    """Exchange authorization code for access/refresh tokens."""
    data = {
        "client_id": client_id,
        "client_secret": client_secret,
        "code": code,
        "redirect_uri": redirect_uri,
        "grant_type": "authorization_code",
    }
    req = urllib.request.Request(
        TOKEN_URL,
        data=urllib.parse.urlencode(data).encode(),
        headers={"Content-Type": "application/x-www-form-urlencoded"},
    )
    with urllib.request.urlopen(req) as response:
        return json.loads(response.read().decode())


def save_env_file(env_path: Path, client_id: str, client_secret: str, refresh_token: str):
    """Save credentials to .env file."""
    content = f"""# Chrome Web Store API Credentials
# Generated by get-cws-refresh-token.py
# DO NOT COMMIT TO GIT - add .env.cws to .gitignore

CWS_CLIENT_ID={client_id}
CWS_CLIENT_SECRET={client_secret}
CWS_REFRESH_TOKEN={refresh_token}
CWS_EXTENSION_ID=hgkfghgifkifgmklfgglilnmjglojonm
"""
    env_path.write_text(content)
    env_path.chmod(0o600)
    print(f"Credentials saved to {env_path} (permissions set to 600)")


def main():
    parser = argparse.ArgumentParser(
        description="Obtain Chrome Web Store refresh token via OAuth 2.0",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Setup:
1. Go to Google Cloud Console: https://console.cloud.google.com/
2. Create/select a project
3. Enable "Chrome Web Store API"
4. Go to APIs & Services -> Credentials
5. Create OAuth 2.0 Client ID (Web application)
6. Add authorized redirect URI: http://localhost:8080/callback
7. Note the Client ID and Client Secret

Run:
    python3 tools/get-cws-refresh-token.py --client-id YOUR_ID --client-secret YOUR_SECRET

This will:
1. Open browser for Google OAuth consent
2. Receive callback on localhost:8080
3. Exchange code for refresh token
4. Save credentials to .env.cws (gitignored)
        """,
    )
    parser.add_argument("--client-id", required=True, help="OAuth 2.0 Client ID")
    parser.add_argument("--client-secret", required=True, help="OAuth 2.0 Client Secret")
    parser.add_argument(
        "--redirect-uri",
        default="http://localhost:8080/callback",
        help="OAuth redirect URI (must match Cloud Console config)",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=8080,
        help="Local server port for callback",
    )
    parser.add_argument(
        "--env-file",
        type=Path,
        default=Path(".env.cws"),
        help="Output .env file path",
    )

    args = parser.parse_args()

    project_root = Path(__file__).resolve().parents[1]
    env_path = args.env_file if args.env_file.is_absolute() else project_root / args.env_file

    # Build authorization URL
    auth_params = {
        "client_id": args.client_id,
        "redirect_uri": args.redirect_uri,
        "response_type": "code",
        "scope": " ".join(SCOPES),
        "access_type": "offline",
        "prompt": "consent",
        "state": secrets.token_urlsafe(16),
    }
    auth_url = f"{AUTH_URL}?{urllib.parse.urlencode(auth_params)}"

    print("=" * 60)
    print("Chrome Web Store OAuth 2.0 Authorization")
    print("=" * 60)
    print(f"\nOpening browser for authorization...")
    print(f"If browser doesn't open, visit:\n{auth_url}\n")

    # Open browser
    import webbrowser
    webbrowser.open(auth_url)

    # Start local server and wait for callback
    print(f"Waiting for callback on http://localhost:{args.port}/callback...")
    try:
        auth_code = run_local_server(args.port)
    except KeyboardInterrupt:
        print("\nCancelled by user")
        return 1
    except Exception as e:
        print(f"\nError: {e}")
        return 1

    print(f"Received authorization code")

    # Exchange for tokens
    print("Exchanging code for tokens...")
    try:
        tokens = exchange_code_for_tokens(
            args.client_id, args.client_secret, auth_code, args.redirect_uri
        )
    except urllib.error.HTTPError as e:
        print(f"Token exchange failed: {e.read().decode()}")
        return 1

    refresh_token = tokens.get("refresh_token")
    if not refresh_token:
        print("ERROR: No refresh token in response. Try adding 'prompt=consent' to auth URL.")
        print(f"Response: {json.dumps(tokens, indent=2)}")
        return 1

    access_token = tokens.get("access_token")
    expires_in = tokens.get("expires_in", 3600)

    print(f"Access token obtained (expires in {expires_in}s)")
    print(f"Refresh token obtained")

    # Save credentials
    save_env_file(env_path, args.client_id, args.client_secret, refresh_token)

    print("\n" + "=" * 60)
    print("SUCCESS! You can now use upload-cws.py")
    print("=" * 60)
    print(f"\nTest upload (dry run):")
    print(f"  python3 tools/upload-cws.py --zip-path releases/v2.4.0/notable-reader-extension-2.4.0.zip --dry-run")
    print(f"\nReal upload (draft):")
    print(f"  python3 tools/upload-cws.py --zip-path releases/v2.4.0/notable-reader-extension-2.4.0.zip")
    print(f"\nUpload and publish:")
    print(f"  python3 tools/upload-cws.py --zip-path releases/v2.4.0/notable-reader-extension-2.4.0.zip --publish")

    return 0


if __name__ == "__main__":
    sys.exit(main())